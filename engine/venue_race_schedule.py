def approx_post_time_str(venue_name: str, race_no: int) -> Optional[str]:
    """会場名・レース番号(1-12)から概算の締切予定時刻"HH:MM"を返す。無ければNone。"""
    times = APPROX_POST_TIMES.get(venue_name)
    if not times:
        return None
    try:
        idx = int(race_no) - 1
    except Exception:
        return None
    if idx < 0 or idx >= len(times):
        return None
    return times[idx]


def approx_post_datetime(venue_name: str, date_str: str, race_no: int) -> Optional[datetime]:
    """date_str: "YYYYMMDD"。会場・日付・レース番号から概算のdatetimeを返す。"""
    t = approx_post_time_str(venue_name, race_no)
    if t is None:
        return None
    try:
        base = datetime.strptime(str(date_str).strip(), "%Y%m%d")
        hh, mm = t.split(":")
        return base + timedelta(hours=int(hh), minutes=int(mm))
    except Exception:
        return None
