def _first_lane(combo: str) -> str:
    return str(combo).split("-")[0].strip()


def apply_lane_correction(prob_map: Dict[str, float], venue: str | None = None) -> Dict[str, float]:
    """1レース分のcombo->prob辞書にレーン別補正を掛け、合計が1になるよう再正規化する。

    engine.prob_calibrator.calibrate_prob_map の後に適用する想定
    (この順序でROI検証済み、詳細はモジュールdocstring参照)。
    """
    if not prob_map:
        return dict(prob_map)

    mult_map = GLOBAL_LANE_MULT
    if venue is not None:
        v = str(venue).strip()
        for name, m in VENUE_LANE_MULT.items():
            if name in v:
                mult_map = m
                break

    corrected = {
        combo: float(p) * mult_map.get(_first_lane(combo), 1.0)
        for combo, p in prob_map.items()
    }
    total = sum(corrected.values())
    if total <= 0:
        return dict(prob_map)

    return {combo: v / total for combo, v in corrected.items()}
